"""
tech_news_crawler.py
====================

This script provides a simple framework for automatically gathering
technology‑related news articles and research updates from a set of RSS
feeds.  It leverages the widely used ``feedparser`` library to fetch
and parse RSS or Atom feeds and uses ``BeautifulSoup`` from
``bs4`` to strip HTML from article summaries.  The script can be
extended to support additional feeds, including unofficial feeds for
WeChat public accounts generated by community projects such as
``WeChat‑Feeds`` (see the accompanying documentation for links).

**Key features**

* A configurable list of RSS/Atom feed URLs covering major technology
  news outlets (The Verge, Ars Technica, TechCrunch, Hacker News, etc.),
  popular AI/tech newsletters (ByteByteGo, Ben's Bites), curated
  discovery sites (Product Hunt), venture capital blogs, personal
  technical blogs, and research journals (MIT Technology Review and
  Nature).  The list can be edited to include additional sources or
  WeChat RSS feeds generated via third‑party services.

* A ``fetch_feed`` function that retrieves and parses each feed using
  ``feedparser``, extracting commonly available fields such as
  ``title``, ``link``, ``summary`` and ``published``.  When a
  ``content:encoded`` tag is present (common in WordPress feeds) it is
  preferred over the shorter summary.

* Automatic removal of HTML tags from the summary using
  ``BeautifulSoup`` to produce clean, plain‑text descriptions.

* A ``filter_articles`` function that optionally filters the list of
  articles by keywords (for example, ``['breakthrough', '突破', '重大']``)
  to focus on major breakthroughs or specific topics.

* A ``save_as_markdown`` helper that writes the collected articles
  to a markdown file.  Each entry includes the publication date,
  source, title and summary with a hyperlink back to the original
  article.

Usage
-----

1. Install the dependencies.  From a terminal on a machine with
   Internet access run::

       pip install feedparser beautifulsoup4

2. Adjust the ``FEED_URLS`` list below.  You can add or remove any
   RSS/Atom feeds.  To include WeChat public accounts you must first
   obtain an RSS feed URL; projects such as `wechat‑feeds` provide
   static RSS files on GitHub for many public accounts.

3. Execute the script.  By default it will print the titles and
   publication dates of recent articles.  You can call
   ``save_as_markdown`` to persist the results.

The functions are written to be modular so you can integrate them into
larger automation workflows (e.g. scheduled jobs, web services or
notebooks).
"""

from __future__ import annotations

import datetime

import logging

# Configure basic logging.  You can adjust the level to DEBUG for
# verbose output when troubleshooting.
logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")

def strip_html(html: str) -> str:
    """Remove HTML tags from a snippet using BeautifulSoup.

    Parameters
    ----------
    html : str
        The raw HTML fragment extracted from an RSS feed.

    Returns
    -------
    str
        Plain text with tags removed.
    """
    soup = BeautifulSoup(html, "html.parser")
    return soup.get_text(separator=" ", strip=True)

def fetch_feed(url: str) -> List[Dict[str, Any]]:
    """Fetch a single RSS/Atom feed and extract article metadata.

    Parameters
    ----------
    url : str
        The RSS or Atom feed URL.

    Returns
    -------
    List[Dict[str, Any]]
        A list of article dictionaries.  Each dictionary contains
        ``source`` (the feed URL), ``title``, ``link``, ``published``
        (as a ``datetime`` object if available) and ``summary``.
    """
    logging.debug("Fetching feed %s", url)
    parsed = feedparser.parse(url)
    articles: List[Dict[str, Any]] = []
    for entry in parsed.entries:
        title: str = entry.get("title", "").strip()
        link: str = entry.get("link", "").strip()
        # Determine publication date if available
        published_parsed = entry.get("published_parsed") or entry.get("updated_parsed")
        if published_parsed:
            published = datetime.datetime(*published_parsed[:6])
        else:
            published = None
        # Prefer full content over summary when present
        if "content" in entry and entry.content:
            content_html = entry.content[0].value
        elif "summary" in entry:
            content_html = entry.summary
        else:
            content_html = ""
        summary = strip_html(content_html)
        articles.append(
            {
                "source": parsed.feed.get("title", url),
                "feed_url": url,
                "title": title,
                "link": link,
                "published": published,
                "summary": summary,
            }
        )
    logging.info("Fetched %d articles from %s", len(articles), url)
    return articles

def fetch_all_feeds(urls: Iterable[str]) -> List[Dict[str, Any]]:
    """Fetch multiple feeds and combine the articles into a single list.

    Parameters
    ----------
    urls : iterable of str
        A collection of RSS or Atom feed URLs.

    Returns
    -------
    List[Dict[str, Any]]
        All articles from the provided feeds.  The list is unsorted.
    """
    all_articles: List[Dict[str, Any]] = []
    for url in urls:
        try:
            feed_articles = fetch_feed(url)
            all_articles.extend(feed_articles)
        except Exception as exc:
            logging.error("Error fetching feed %s: %s", url, exc)
    return all_articles

def filter_articles(
    articles: Iterable[Dict[str, Any]], keywords: Optional[List[str]] = None
) -> List[Dict[str, Any]]:
    """Filter a list of articles by one or more keywords.

    Parameters
    ----------
    articles : iterable of dict
        The article dictionaries produced by ``fetch_feed`` or
        ``fetch_all_feeds``.
    keywords : list of str or None, optional
        If provided, only articles whose titles or summaries contain at
        least one of the keywords (case‑insensitive) will be returned.
        When ``None``, no filtering is applied.

    Returns
    -------
    list of dict
        The filtered articles.  The ordering is unchanged from the
        original list.
    """
    if not keywords:
        return list(articles)
    keywords_lower = [kw.lower() for kw in keywords]
    filtered: List[Dict[str, Any]] = []
    for article in articles:
        haystack = f"{article.get('title', '')} {article.get('summary', '')}".lower()
        if any(kw in haystack for kw in keywords_lower):
            filtered.append(article)
    logging.info("Filtered down to %d articles using keywords %s", len(filtered), keywords)
    return filtered

def sort_articles_by_date(articles: Iterable[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Sort articles by their publication date in descending order.

    Articles without a publication date are placed at the end of the list.
    """
    return sorted(
        articles,
        key=lambda a: a.get("published") or datetime.datetime.min,
        reverse=True,
    )

def save_as_markdown(
    articles: Iterable[Dict[str, Any]], filename: str = "tech_news.md"
) -> None:
    """Save a collection of articles to a Markdown file.

    Parameters
    ----------
    articles : iterable of dict
        The articles to save, ideally sorted by date.
    filename : str, optional
        Destination filename for the Markdown output.  Defaults
        to ``tech_news.md``.
    """
    lines: List[str] = []
    for article in articles:
        pub_date = article.get("published")
        date_str = pub_date.strftime("%Y-%m-%d %H:%M") if pub_date else "Unknown date"
        lines.append(f"### {article['title']}")
        lines.append(f"- **Date:** {date_str}")
        lines.append(f"- **Source:** {article['source']}")
        lines.append(f"- **Link:** [{article['link']}]({article['link']})")
        if article.get("summary"):
            lines.append(f"- **Summary:** {article['summary']}")
        lines.append("")  # blank line between entries
    with open(filename, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    logging.info("Saved %d articles to %s", len(list(articles)), filename)

